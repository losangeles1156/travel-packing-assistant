import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';

test('flight and lodging records require confirmation and survive backup restore', async ({ page }) => {
  await page.goto('/');
  await page.getByPlaceholder('例如：東京, 日本').fill('測試旅程');
  await page.getByRole('button', { name: /建立旅程/ }).click();
  const area=page.getByRole('region',{name:'航班與住宿'});
  await area.getByRole('button',{name:'＋ 新增航班'}).click();
  await area.getByText('貼上訂單文字擷取草稿').click();
  await area.getByLabel('訂單文字').fill('航空公司：測試航空\n航班號碼：AB123\n出發機場：台中\n抵達機場：神戶\n護照號碼：SYNTHETIC_SECRET');
  await area.getByRole('button',{name:'擷取草稿'}).click();
  await expect(area.locator('article')).toHaveCount(0);
  await expect(area.getByLabel('航班號碼（選填）')).toHaveValue('AB123');
  await area.getByRole('button',{name:'確認加入旅程'}).click();
  await area.getByRole('button',{name:'＋ 新增航班'}).click();
  await area.getByLabel('航空公司或航班名稱').fill('第二航空');
  await area.getByRole('button',{name:'確認加入旅程'}).click();
  for (const name of ['大阪測試飯店','東京測試飯店']) {
    await area.getByRole('button',{name:'＋ 新增住宿'}).click();
    await area.getByLabel('住宿名稱').fill(name);
    await area.getByRole('button',{name:'確認加入旅程'}).click();
  }
  await expect(area.locator('article')).toHaveCount(4);
  const flight = area.locator('article').filter({hasText:'測試航空'});
  await flight.getByText('航班有變動時怎麼辦？').click();
  await flight.getByRole('button',{name:'航班延誤'}).click();
  await expect(flight.getByText(/2 筆住宿記錄/)).toBeVisible();
  await flight.getByRole('button',{name:'航班取消'}).click();
  await expect(flight.getByText(/改票或退款/)).toBeVisible();
  const changes=page.getByRole('region',{name:'旅程變動'});
  await changes.getByRole('button',{name:'＋ 記錄航班變動'}).click();
  await changes.getByLabel('選擇航班').selectOption({index:1});
  await changes.getByLabel('變動類型').selectOption('rescheduled');
  await changes.getByLabel('新出發日期（選填）').fill('2026-12-02');
  await changes.getByLabel('新出發時間（選填）').fill('10:00');
  await changes.getByLabel('新出發時區（選填）').fill('Asia/Tokyo');
  await changes.getByLabel('資訊來源').fill('航空公司測試通知');
  await changes.getByRole('button',{name:'確認記錄變動'}).click();
  await expect(changes.getByText('航空公司測試通知',{exact:false})).toBeVisible();
  const transport=page.getByRole('region',{name:'機場交通安排'});
  await transport.getByRole('button',{name:'＋ 新增交通安排'}).click();
  await transport.getByLabel('交通方式').selectOption('transfer');
  await transport.getByLabel('交通名稱').fill('測試機場接送');
  await transport.getByLabel('聯絡方式').fill('測試服務商');
  await transport.getByLabel('關聯航班（選填）').selectOption({index:1});
  await transport.getByRole('button',{name:'確認交通安排'}).click();
  await changes.getByText('查看需要確認的事項').click();
  await expect(changes.getByText(/確認測試機場接送原安排.*聯絡方式：測試服務商/)).toBeVisible();
  const protection=page.getByRole('region',{name:'通訊與保險守護'});
  await protection.getByRole('button',{name:'編輯守護資料'}).click();
  await protection.getByLabel('裝置型號').fill('測試裝置');
  await protection.getByLabel('eSIM 相容性').selectOption('unsupported');
  await protection.getByLabel('上網方式').selectOption('esim');
  await protection.getByLabel('已確認到期日期').fill('2026-12-02');
  await protection.getByLabel('已確認到期時間').fill('09:00');
  await protection.getByLabel('到期時區（例如 Asia/Tokyo）').fill('Asia/Tokyo');
  await protection.getByLabel('保險公司', {exact:true}).fill('測試保險公司');
  await protection.getByRole('button',{name:'確認守護資料'}).click();
  await expect(protection.getByText(/已記錄裝置不支援 eSIM/)).toBeVisible();
  await protection.getByLabel('選擇已記錄的航班變動').selectOption({index:1});
  await expect(protection.getByText(/到期時間不晚於新出發時間/)).toBeVisible();
  await area.getByRole('button',{name:'編輯 東京測試飯店'}).click();
  await area.getByLabel('住宿地址').fill('東京測試地址');
  await area.getByRole('button',{name:'確認修改'}).click();
  await expect(page.getByText('已儲存至本機',{exact:true})).toBeVisible();
  await page.reload();
  await expect(area.locator('article')).toHaveCount(4);
  await expect(area.getByText('東京測試地址')).toBeVisible();
  await expect(changes.getByText('航空公司測試通知',{exact:false})).toBeVisible();
  await expect(transport.getByText('測試機場接送')).toBeVisible();
  await expect(protection.getByText('測試保險公司')).toBeVisible();
  await page.getByRole('button',{name:'工具'}).click();
  const backup=page.locator('section[aria-label="本機資料備份"]');
  await backup.locator('summary').click();
  const [download]=await Promise.all([page.waitForEvent('download'),backup.getByRole('button',{name:'下載備份',exact:true}).click()]);
  const path=await download.path(); const raw=await fs.readFile(path,'utf8');
  expect(JSON.parse(raw).version).toBe(11); expect(raw).not.toContain('SYNTHETIC_SECRET');
  page.once('dialog',dialog=>dialog.accept());
  await backup.getByRole('button',{name:'刪除全部本機資料'}).click();
  await expect(backup.getByText('清單與對應舊版副本已刪除',{exact:false})).toBeVisible();
  await backup.locator('input[type=file]').setInputFiles(path);
  await backup.getByRole('button',{name:'確認合併'}).click();
  await expect(backup.getByText('匯入完成。',{exact:true})).toBeVisible();
  await expect(area.locator('article')).toHaveCount(4);
  await expect(area.getByText('東京測試地址')).toBeVisible();
  await expect(changes.getByText('航空公司測試通知',{exact:false})).toBeVisible();
  await expect(transport.getByText('測試機場接送')).toBeVisible();
  await expect(protection.getByText('測試保險公司')).toBeVisible();
});

test('flight and lodging records remain isolated between trips', async ({ page }) => {
  await page.goto('/');
  await page.getByPlaceholder('例如：東京, 日本').fill('隔離測試甲');
  await page.getByRole('button', { name: /建立旅程/ }).click();
  const area = page.getByRole('region', { name: '航班與住宿' });
  await area.getByRole('button', { name: '＋ 新增航班' }).click();
  await area.getByLabel('航空公司或航班名稱').fill('甲的航班');
  await area.getByRole('button', { name: '確認加入旅程' }).click();
  await page.getByRole('button', { name: '切換／新增旅程' }).click();
  await page.getByPlaceholder('例如：東京, 日本').fill('隔離測試乙');
  await page.getByRole('button', { name: /建立旅程/ }).click();
  await expect(area.locator('article')).toHaveCount(0);
  await area.getByRole('button', { name: '＋ 新增住宿' }).click();
  await area.getByLabel('住宿名稱').fill('乙的住宿');
  await area.getByRole('button', { name: '確認加入旅程' }).click();
  await page.getByRole('button', { name: '切換／新增旅程' }).click();
  await page.getByRole('button', { name: /隔離測試甲/ }).click();
  await expect(area.getByRole('heading', { name: '甲的航班' })).toBeVisible();
  await expect(area.getByText('乙的住宿')).toHaveCount(0);
  await page.getByRole('button', { name: '切換／新增旅程' }).click();
  await page.getByRole('button', { name: /隔離測試乙/ }).click();
  await expect(area.getByRole('heading', { name: '乙的住宿' })).toBeVisible();
  await expect(area.getByText('甲的航班')).toHaveCount(0);
});

test('flight and lodging can be created, edited and reopened offline', async ({ page, context }) => {
  test.skip(process.env.E2E_PWA !== '1', 'Requires production preview and service worker');
  await page.goto('/');
  await page.evaluate(() => navigator.serviceWorker.ready);
  await page.reload();
  await context.setOffline(true);
  try {
    await page.reload();
    await page.getByPlaceholder('例如：東京, 日本').fill('離線航班測試');
    await page.getByRole('button', { name: /建立旅程/ }).click();
    const area = page.getByRole('region', { name: '航班與住宿' });
    await area.getByRole('button', { name: '＋ 新增航班' }).click();
    await area.getByLabel('航空公司或航班名稱').fill('離線測試航空');
    await area.getByRole('button', { name: '確認加入旅程' }).click();
    await area.getByRole('button', { name: '＋ 新增住宿' }).click();
    await area.getByLabel('住宿名稱').fill('離線測試住宿');
    await area.getByRole('button', { name: '確認加入旅程' }).click();
    await area.getByRole('button', { name: '編輯 離線測試住宿' }).click();
    await area.getByLabel('住宿地址').fill('離線修改地址');
    await area.getByRole('button', { name: '確認修改' }).click();
    await page.getByRole('button', { name: /法規查詢/ }).click();
    await expect(page.getByRole('heading', { name: '法規查詢' })).toBeVisible();
    await page.reload();
    await expect(area.getByRole('heading', { name: '離線測試航空' })).toBeVisible();
    await expect(area.getByText('離線修改地址')).toBeVisible();
  } finally { await context.setOffline(false); }
});
